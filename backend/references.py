"""Nano Banana mayor reference images (issue #7).

Each attempt edits the stored original frame according to a compiled Carbon
edit. Output is decoded, checked, normalized in code to exactly 1280x720 (16:9,
Genie's documented output size) and stored with its own hash, ModelCall and
cost. Failed attempts are recorded too. This stage never creates a Genie
session; that requires an accepted reference gate (#8).
"""
from __future__ import annotations

import asyncio
import base64
from io import BytesIO

from PIL import Image
from pydantic import BaseModel, ConfigDict

from .artifacts import ArtifactError, ArtifactStore, new_id, sha256, utcnow
from .contracts import ReferenceImage
from .edits import EditBundle
from .gateway import CallContext, GatewayError, ModelGateway, Service
from .gateway.contracts import ErrorCode
from .modelcalls import from_error, from_result

PROMPT_ID = "nano-banana.mayor-reference.v1"
TARGET_SIZE = (1280, 720)  # Genie docs: 16:9 starting image; output is fixed at 1280x720.
MAX_ASPECT_DEVIATION = 0.03  # larger deviations are malformed, not cropped
MAX_ATTEMPTS = 3  # initial attempt plus at most two gate-driven re-edits
# Local transport bound, not a documented Genie limit (WebSocket states none;
# WebRTC seeds must stay under 48 KB and are not used here).
GENIE_TRANSPORT = {"mimeTypes": ("image/png", "image/jpeg"), "width": 1280, "height": 720,
                   "maxBytes": 8 * 1024 * 1024, "channel": "websocket"}

STYLES = {
    "photoreal": {"status": "supported",
                  "prompt": "Photorealistic, matching the original camera's lighting, lens and weather."},
    "cel_shaded": {"status": "supported",
                   "prompt": "Clean cel-shaded illustration with flat colors and crisp outlines; same composition."},
    "retro_16bit": {"status": "experimental", "prompt": "16-bit pixel-art game screenshot; same composition."},
    "claymation": {"status": "experimental", "prompt": "Claymation miniature set; same composition."},
    "video_game": {"status": "experimental", "prompt": "Modern open-world video-game render; same composition."},
}

INTERPRETATIONS = [
    "Pixels in edited regions are generated by Nano Banana, not recovered street geometry.",
    "Surfaces hidden in the original frame (behind vehicles, beyond the frame edge) are invented if shown.",
    "Any change of viewpoint, lens or framing relative to the original frame is a generated interpretation.",
]


class ReferenceError(ArtifactError):
    pass


_locks: dict[tuple[str, str], asyncio.Lock] = {}


class AttemptRecord(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)
    id: str
    streetEditId: str
    captureId: str
    style: str
    styleStatus: str
    attempt: int
    status: str  # "generated" | "failed" | "malformed"
    feedback: str | None
    sourceFrameSha256: str
    referenceImage: ReferenceImage | None
    modelCall: dict
    error: dict | None = None
    raw: dict | None = None
    normalization: dict | None = None
    genieTransport: dict | None = None
    interpretations: list[str]


def attempts(store: ArtifactStore, street_edit_id: str, style: str | None = None) -> list[dict]:
    rows = [r for r in store.list("references") if r["streetEditId"] == street_edit_id
            and (style is None or r["style"] == style)]
    return sorted(rows, key=lambda r: (r["style"], r["attempt"]))


def normalize(data: bytes) -> tuple[bytes, dict, dict]:
    """Center-crop to exact 16:9 and resize to TARGET_SIZE. Raises ReferenceError if malformed."""
    try:
        with Image.open(BytesIO(data)) as image:
            fmt, (w, h) = image.format, image.size
            image.load()
            rgb = image.convert("RGB")
    except (OSError, ValueError, Image.DecompressionBombError):
        raise ReferenceError("Nano Banana returned an undecodable image.", status=502) from None
    raw = {"sha256": sha256(data), "format": fmt, "width": w, "height": h}
    if w < 640 or h < 360:
        raise ReferenceError("Nano Banana returned an image smaller than 640x360.", status=502, **raw)
    if abs((w / h) / (16 / 9) - 1) > MAX_ASPECT_DEVIATION:
        raise ReferenceError("Nano Banana returned an image that is not approximately 16:9.", status=502, **raw)
    k = min(w // 16, h // 9)
    cw, ch = 16 * k, 9 * k
    left, top = (w - cw) // 2, (h - ch) // 2
    out = rgb.crop((left, top, left + cw, top + ch)).resize(TARGET_SIZE, Image.Resampling.LANCZOS)
    buffer = BytesIO()
    out.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue(), raw, {"crop": [left, top, cw, ch], "resizedTo": list(TARGET_SIZE),
                                    "encoding": "png", "method": "center-crop to exact 16:9, Lanczos resize"}


def validate_transport(data: bytes, mime_type: str) -> dict:
    """Check the exact bytes that would be sent to Genie as reference_image."""
    if mime_type not in GENIE_TRANSPORT["mimeTypes"]:
        raise ReferenceError("Genie reference must be PNG or JPEG.", status=422, mimeType=mime_type)
    if len(data) > GENIE_TRANSPORT["maxBytes"]:
        raise ReferenceError("Genie reference exceeds the transport byte bound.", status=422, bytes=len(data))
    with Image.open(BytesIO(data)) as image:
        size, fmt = image.size, image.format
    if size != (GENIE_TRANSPORT["width"], GENIE_TRANSPORT["height"]) or size[0] * 9 != size[1] * 16:
        raise ReferenceError("Genie reference must be exactly 1280x720.", status=422, size=list(size))
    if {"PNG": "image/png", "JPEG": "image/jpeg"}.get(fmt) != mime_type:
        raise ReferenceError("Genie reference bytes do not match their MIME type.", status=422)
    return {"mimeType": mime_type, "width": size[0], "height": size[1], "bytes": len(data),
            "sha256": sha256(data), "channel": GENIE_TRANSPORT["channel"]}


def genie_payload(store: ArtifactStore, record: dict) -> dict:
    """The world_setup.reference_image value, re-verified from stored bytes."""
    ref = record["referenceImage"]
    data = store.get_blob(ref["imageSha256"])
    validate_transport(data, record["genieTransport"]["mimeType"])
    return {"mime_type": record["genieTransport"]["mimeType"], "data": base64.b64encode(data).decode()}


def build_prompt(bundle: EditBundle, style: str, feedback: str | None) -> str:
    preserved = [f"{a}" for a in bundle.preservedAnchorIds]
    lines = [
        "Edit this exact street-camera frame. Keep the camera position, framing, buildings, sidewalks and every"
        " crosswalk where they are. Change only what the instructions say.",
        "EDIT: " + (bundle.imageInstructions or ""),
        "PRESERVE anchors (from the evidence list): " + (", ".join(preserved) or "none listed"),
        "Operations: " + "; ".join(f"{op.op} {op.target}: {op.description}" for op in bundle.streetEdit.operations),
        "STYLE: " + STYLES[style]["prompt"],
        "Output one 16:9 image. No text overlays, captions, logos, or identifiable faces or license plates.",
    ]
    if feedback:
        lines.append("PREVIOUS ATTEMPT WAS REJECTED BY THE REVIEW GATE. Fix exactly this: " + feedback)
    return "\n".join(lines)


async def generate_reference(gateway: ModelGateway, store: ArtifactStore, bundle: EditBundle, *, style: str,
                             feedback: str | None = None, allow_experimental: bool = False,
                             purpose: str = "development") -> AttemptRecord:
    # Serialize attempts per edit/style so the attempt cap cannot be raced.
    async with _locks.setdefault((bundle.streetEdit.id, style), asyncio.Lock()):
        return await _generate(gateway, store, bundle, style=style, feedback=feedback,
                               allow_experimental=allow_experimental, purpose=purpose)


async def _generate(gateway, store, bundle, *, style, feedback, allow_experimental, purpose) -> AttemptRecord:
    edit = bundle.streetEdit
    if edit.status != "compiled":
        raise ReferenceError("Only compiled street edits can be rendered.", status=409, editStatus=edit.status)
    if style not in STYLES:
        raise ReferenceError("Unknown style.", status=422, style=style, supported=list(STYLES))
    if STYLES[style]["status"] != "supported" and not allow_experimental:
        raise ReferenceError("This style is experimental; pass allowExperimental to try it.", status=422, style=style)
    if not bundle.sourceFrame:
        raise ReferenceError("The edit has no stored source frame to edit.", status=409)
    previous = attempts(store, edit.id, style)
    if len(previous) >= MAX_ATTEMPTS:
        raise ReferenceError("Reference attempts for this edit and style are exhausted.", status=409,
                             attempts=len(previous), maxAttempts=MAX_ATTEMPTS)
    frame = bundle.sourceFrame
    frame_bytes = store.get_blob(frame["frameSha256"])
    edit_hash = sha256(edit.model_dump_json().encode())
    domain = [frame["frameSha256"], edit_hash, *([bundle.captureMediaSha256] if bundle.captureMediaSha256 else [])]
    prompt = build_prompt(bundle, style, feedback)
    context = CallContext(episode_id=bundle.captureId, prompt_id=PROMPT_ID, capture_id=bundle.captureId,
                          source_id=bundle.sourceId or bundle.captureId, purpose=purpose)
    record_id = new_id("ref")
    base = dict(id=record_id, streetEditId=edit.id, captureId=bundle.captureId, style=style,
                styleStatus=STYLES[style]["status"], attempt=len(previous) + 1, feedback=feedback,
                sourceFrameSha256=frame["frameSha256"], interpretations=INTERPRETATIONS)
    requested = utcnow()
    try:
        result = await gateway.generate(Service.NANO_BANANA, stage="reference", context=context, input_value=[
            {"type": "text", "text": prompt},
            {"type": "image", "mime_type": frame["mimeType"], "data": base64.b64encode(frame_bytes).decode()}])
    except (GatewayError, asyncio.CancelledError) as exc:
        error = (GatewayError(ErrorCode.CANCELLED, request_id=getattr(exc, "request_id", None))
                 if isinstance(exc, asyncio.CancelledError) else exc)
        call = from_error(gateway, Service.NANO_BANANA, error, prompt_id=PROMPT_ID, domain_hashes=domain,
                          requested_at=requested, completed_at=utcnow())
        record = AttemptRecord(**base, status="failed", referenceImage=None, modelCall=call.model_dump(mode="json"),
                               error=error.public())
        store.put("references", record_id, record)
        if isinstance(exc, asyncio.CancelledError):
            raise  # counted and retained, but cancellation must still reach the caller
        return record
    call = from_result(gateway, Service.NANO_BANANA, result, prompt_id=PROMPT_ID, domain_hashes=domain,
                       requested_at=requested, completed_at=utcnow())
    try:
        raw_bytes = base64.b64decode(result.output["data"], validate=True)
        if sha256(raw_bytes) == frame["frameSha256"]:
            raise ReferenceError("Nano Banana returned the source frame unchanged.", status=502)
        data, raw, normalization = normalize(raw_bytes)
        transport = validate_transport(data, "image/png")
    except (ReferenceError, KeyError, ValueError, TypeError) as exc:
        detail = exc.detail if isinstance(exc, ReferenceError) else {"error": "Image output was malformed."}
        record = AttemptRecord(**base, status="malformed", referenceImage=None,
                               modelCall=call.model_dump(mode="json"), error=detail)
        store.put("references", record_id, record)
        return record
    image_hash = store.put_blob(data)
    store.put_blob(raw_bytes)  # the unnormalized model output stays reviewable
    reference = ReferenceImage(id=record_id, captureId=bundle.captureId, streetEditId=edit.id, style=style,
                               attempt=base["attempt"], modelCall=call, imageSha256=image_hash,
                               width=TARGET_SIZE[0], height=TARGET_SIZE[1])
    record = AttemptRecord(**base, status="generated", referenceImage=reference,
                           modelCall=call.model_dump(mode="json"), raw=raw, normalization=normalization,
                           genieTransport=transport)
    store.put("references", record_id, record)
    return record
