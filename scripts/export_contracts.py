"""Generate frontend types and JSON Schema from the canonical Python contracts."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.contracts import VerticalSlice  # noqa: E402


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(typescript(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        fields = [f"  {name}{'' if name in required else '?'}: {typescript(value)};" for name, value in schema.get("properties", {}).items()]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generated_files():
    schema = VerticalSlice.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://element119.local/contracts/1.0"
    definitions = schema.get("$defs", {})
    declarations = ["// Generated by scripts/export_contracts.py; edit backend/contracts.py instead.\n"]
    declarations += [f"export type {name} = {typescript(value)};\n" for name, value in definitions.items()]
    declarations.append(f"export type VerticalSlice = {typescript(schema)};\n")
    return {
        ROOT / "src/contracts/schema.json": json.dumps(schema, indent=2) + "\n",
        ROOT / "src/contracts/types.ts": "\n".join(declarations),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if committed generated files are stale")
    args = parser.parse_args()
    stale = []
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        sys.exit("Stale generated contracts: " + ", ".join(stale))


if __name__ == "__main__":
    main()
